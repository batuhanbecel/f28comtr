const fs = require('fs');
const path = require('path');

const portfoliosPath = path.join(__dirname, '..', 'public', 'portfolios');
const aiImagesPath = path.join(__dirname, '..', 'public', 'ai-images');
const partnerLogosPath = path.join(__dirname, '..', 'public', 'logos', 'brands', 'partners');
const clientLogosPath = path.join(__dirname, '..', 'public', 'logos', 'brands', 'clients');
const manifest = {};

try {
  const entries = fs.readdirSync(portfoliosPath);
  const photographers = entries.filter(d => {
    if (d === 'previews') return false;
    const stat = fs.statSync(path.join(portfoliosPath, d));
    return stat.isDirectory();
  });

  for (const photographer of photographers) {
    const folderPath = path.join(portfoliosPath, photographer);
    const files = fs.readdirSync(folderPath)
      .filter(f => /\.(jpg|jpeg|png|webp)$/i.test(f))
      .filter(f => {
        try {
          const stat = fs.statSync(path.join(folderPath, f));
          return stat.size > 1024;
        } catch {
          return false;
        }
      })
      .sort()
      .map(f => `/portfolios/${photographer}/${encodeURIComponent(f)}`);

    manifest[photographer] = files;
    console.log(`  ${photographer}: ${files.length} images`);
  }
} catch (err) {
  console.error('Error reading portfolios directory:', err.message);
  process.exit(1);
}

// Also scan AI images
try {
  const aiFiles = fs.readdirSync(aiImagesPath)
    .filter(f => /\.(jpg|jpeg|png|webp)$/i.test(f))
    .filter(f => {
      try {
        const stat = fs.statSync(path.join(aiImagesPath, f));
        return stat.size > 1024;
      } catch {
        return false;
      }
    })
    .sort()
    .map(f => `/ai-images/${encodeURIComponent(f)}`);
  manifest['__ai__'] = aiFiles;
  console.log(`  ai-images: ${aiFiles.length} images`);
} catch {
  manifest['__ai__'] = [];
  console.log('  ai-images: folder not found, skipping');
}

// Scan partner logos
try {
  const partnerFiles = fs.readdirSync(partnerLogosPath)
    .filter(f => /\.(jpg|jpeg|png|webp|svg)$/i.test(f))
    .sort()
    .map(f => `/logos/brands/partners/${encodeURIComponent(f)}`);
  manifest['__partners__'] = partnerFiles;
  console.log(`  partner-logos: ${partnerFiles.length} logos`);
} catch {
  manifest['__partners__'] = [];
  console.log('  partner-logos: folder not found, skipping');
}

// Scan client logos
try {
  const clientFiles = fs.readdirSync(clientLogosPath)
    .filter(f => /\.(jpg|jpeg|png|webp|svg)$/i.test(f))
    .sort()
    .map(f => `/logos/brands/clients/${encodeURIComponent(f)}`);
  manifest['__clients__'] = clientFiles;
  console.log(`  client-logos: ${clientFiles.length} logos`);
} catch {
  manifest['__clients__'] = [];
  console.log('  client-logos: folder not found, skipping');
}

const content = `// Auto-generated by scripts/generate-image-manifest.js — do not edit manually
// Regenerate with: npm run generate-manifest
export const imageManifest: Record<string, string[]> = ${JSON.stringify(manifest, null, 2)};
`;

const outputPath = path.join(__dirname, '..', 'lib', 'image-manifest.ts');
fs.writeFileSync(outputPath, content);
console.log(`\nManifest written to lib/image-manifest.ts (${Object.keys(manifest).length} entries)`);
